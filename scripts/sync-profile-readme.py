#!/usr/bin/env python3
"""Regenerate the shared-packages table in profile/README.md.

The list of packages, what each does and which apps use it come from the wiki's
scripts/shared-frameworks.json (one hand-written source for both pages). Version,
release date, platforms and topics are read from each package's repository.
Only the lines between the two `shared-packages` markers are rewritten.

    GH_TOKEN=$(gh auth token) python3 scripts/sync-profile-readme.py
"""
import base64
import json
import os
import re
import urllib.error
import urllib.request
from pathlib import Path

README = Path(__file__).resolve().parent.parent / "profile" / "README.md"
DATA_URL = "https://raw.githubusercontent.com/Provenance-Emu/wiki/master/scripts/shared-frameworks.json"
WIKI = "https://wiki.provenance-emu.com/help/shared-frameworks"
START, END = "<!-- shared-packages:start -->", "<!-- shared-packages:end -->"
TOKEN = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
SEMVER = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")
PLATFORM = re.compile(r"\.(iOS|tvOS|macOS|watchOS|visionOS)\(\s*(?:\.v|\")([0-9_.]+)")
PLATFORM_ORDER = ["iOS", "tvOS", "macOS", "watchOS", "visionOS"]
# On every package, so they say nothing about one of them.
COMMON_TOPICS = {"swift", "swift-package", "spm", "ios", "tvos", "emulator", "emulation",
                 "retrogaming", "provenance", "xcframework"}


def get(url):
    request = urllib.request.Request(url)
    if "api.github.com" in url:
        request.add_header("Accept", "application/vnd.github+json")
        if TOKEN:
            request.add_header("Authorization", f"Bearer {TOKEN}")
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return None
        raise


def api(path):
    return get(f"https://api.github.com/{path}")


def row(owner, entry):
    name = entry["name"]
    repo = api(f"repos/{owner}/{name}")
    url = repo["html_url"]
    releases = [r for r in api(f"repos/{owner}/{name}/releases?per_page=100") or []
                if SEMVER.match(r["tag_name"]) and not r["draft"] and not r["prerelease"]]
    if releases:
        release = max(releases, key=lambda r: tuple(int(p) for p in SEMVER.match(r["tag_name"]).groups()))
        latest = f"[{release['tag_name']}]({url}/releases/tag/{release['tag_name']})<br><sub>{release['published_at'][:10]}</sub>"
    else:
        tags = [t["name"] for t in api(f"repos/{owner}/{name}/tags?per_page=100") or [] if SEMVER.match(t["name"])]
        tag = max(tags, key=lambda t: tuple(int(p) for p in SEMVER.match(t).groups())) if tags else None
        latest = f"[{tag}]({url}/tree/{tag})" if tag else "unreleased"
    manifest = api(f"repos/{owner}/{name}/contents/Package.swift?ref={repo['default_branch']}")
    found = {}
    if manifest:
        for platform, version in PLATFORM.findall(base64.b64decode(manifest["content"]).decode()):
            found.setdefault(platform, version.replace("_", "."))
    platforms = ", ".join(f"{p} {found[p]}" for p in PLATFORM_ORDER if p in found)
    topics = [t for t in repo.get("topics") or [] if t not in COMMON_TOPICS]
    chips = " ".join(f"[`{t}`](https://github.com/topics/{t})" for t in topics)
    what = entry["summary"] + (f"<br><sub>{chips}</sub>" if chips else "")
    return f"| [{name}]({url}) | {what} | {', '.join(entry['usedBy'])} | {platforms} | {latest} |"


def main():
    data = get(DATA_URL)
    owner = data["organization"]
    block = [START,
             "<!-- Generated by scripts/sync-profile-readme.py; edit the wiki's scripts/shared-frameworks.json instead. -->",
             "| Package | What it does | Used by | Platforms | Latest |",
             "|---------|--------------|---------|-----------|--------|",
             *[row(owner, entry) for entry in data["packages"]],
             END]
    text = README.read_text()
    if START in text:
        updated = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: "\n".join(block), text, flags=re.S)
    else:
        table = re.search(r"\| Package \| What it does \| Used by \| Platforms \| Latest \|\n(?:\|.*\n)+", text)
        updated = text[:table.start()] + "\n".join(block) + "\n" + text[table.end():]
    if updated == text:
        print("profile/README.md is up to date")
        return
    README.write_text(updated)
    print("profile/README.md regenerated")


if __name__ == "__main__":
    main()
